export function expandTopic([title, ...ranges]) {
  const numbers = ranges.flatMap(r => {
    if (typeof r === 'number') return [r];
    return Array.from({ length: r[1] - r[0] + 1 }, (_, i) => r[0] + i);
  });
  return { title, numbers };
}
